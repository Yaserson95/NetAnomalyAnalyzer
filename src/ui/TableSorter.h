#pragma once

#include <QObject>

class QTableWidget;

/**
 * @brief Утилита ручной сортировки строк QTableWidget по клику на заголовок.
 *
 * Не использует встроенную сортировку QTableWidget (она сравнивает только
 * отображаемый текст, поэтому «5.0 МБ» и «100 пакетов» едут неправильно).
 * Вместо этого строки переставляются целиком: числовые значения
 * (сырое число в Qt::UserRole+1) сравниваются как числа, остальные —
 * как текст. Последние строки-ограничители («… и ещё N») всегда
 * остаются внизу. Данные ячеек сохраняются — дополнительные роли
 * (идентификаторы записей, сводки групп) переезжают вместе со строкой.
 */
class TableSorter {
public:
    /** Переставить строки таблицы по колонке.
     *  @param pinnedLastRows число последних строк-ограничителей,
     *         которые всегда остаются внизу. */
    static void sortRows(QTableWidget *table, int column, Qt::SortOrder order,
                         int pinnedLastRows = 0);
    /** Есть ли в колонке числовые значения (Qt::UserRole+1) —
     *  помогает выбрать порядок по умолчанию для новой колонки. */
    static bool columnIsNumeric(const QTableWidget *table, int column);
};
